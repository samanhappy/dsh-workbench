// Build the two plugin halves from their TypeScript sources with esbuild:
//
//   src/host/index.ts    →  index.js       (ESM, node; schemastery inlined)
//   src/client/*         →  lib/client.js  (browser CJS wrapped in the DSH
//                            module-loader factory the host client-modules
//                            service serves into window.__DSH_BOOT__)
//
// The client wrapper mirrors what the official tsdown clientBundle preset
// emits for in-repo client packages: a CJS factory registered through
// window.__ModuleLoader__.load({ id, factory }), where `require` resolves the
// module table (react + @deepseek-ai/dsh-client-ui-primitives here) and
// `module.exports` is the plugin. The bundle only ever type-imports the rest
// of the @deepseek-ai client modules (slots / sessions / uiWorkspace), so no
// profile-roster package needs to be resolvable at build time.
//
// The option builders are exported so tests can rebuild into temp locations
// with the exact production configuration and verify the committed artifacts
// are reproducible. The default build below runs only when executed directly
// (node build.mjs / npm run build), so importing this module never touches the
// committed artifacts.
import { build } from 'esbuild'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const log = (msg) => console.log(msg)

const NOTICE_BANNER = `/*! dsh-workbench — MIT License (see LICENSE).
 * Bundled third-party code: dsh-git-tree (c) 2026 chzisnull (MIT);
 * DeepSeek Harness diff rendering (c) 2026 DeepSeek (MIT);
 * @deepseek-ai/schemastery + @deepseek-ai/cosmokit (c) 2021-present Shigma (MIT);
 * jsdiff (c) 2009-2015 Kevin Decker (BSD-3-Clause);
 * Lucide icons (ISC), Phosphor icons (MIT), Git logo (c) Jason Long (CC BY 3.0).
 * Full texts: THIRD_PARTY_NOTICES.md. */`

/**
 * Host-half esbuild options → index.js (ESM, node).
 *
 * Bundling must not read tsconfig.json: its `paths` map @deepseek-ai/* to a
 * machine-specific absolute DSH install path, and esbuild would bake that
 * resolved location (and its path comment) into the bundle, so the committed
 * artifact could only be reproduced on a machine whose install lives at that
 * exact path. Building against the dedicated `tsconfig.build.json` (no `paths`)
 * pins bundling to the lockfile-pinned node_modules copies, making output
 * byte-reproducible everywhere. Typecheck keeps its own tsconfig (with `paths`)
 * and is unaffected.
 */
export function hostOptions(overrides = {}) {
  return {
    entryPoints: [join(root, 'src', 'host', 'index.ts')],
    outfile: join(root, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    sourcemap: false,
    // Use the dedicated build tsconfig (no `paths`) instead of auto-discovering
    // tsconfig.json, whose `paths` map @deepseek-ai/* to a machine-specific
    // absolute DSH install path — bundling through it would bake that location
    // into the bundle and break reproducibility across machines.
    tsconfig: join(root, 'tsconfig.build.json'),
    banner: { js: NOTICE_BANNER },
    logLevel: 'info',
    ...overrides,
  }
}

export async function buildHostBundle(outfile = join(root, 'index.js'), overrides = {}) {
  await build(hostOptions({ outfile, ...overrides }))
}

/**
 * Client-half esbuild options. `jsx: 'transform'` and the dedicated build
 * tsconfig (no `paths`) pin the JSX transform and resolution explicitly so the
 * bundle does not depend on tsconfig.json state (same reasoning as the host
 * half).
 */
export function clientOptions(overrides = {}) {
  return {
    entryPoints: [join(root, 'src', 'client', 'index.ts')],
    outfile: join(root, 'lib', '_client.bundle.js'),
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    // The loader's module table owns these specifiers at runtime (react is a
    // platform module; ui-primitives ships the Tooltip primitive). Everything
    // else in src/client is bundled in.
    external: ['react', '@deepseek-ai/dsh-client-ui-primitives'],
    loader: { '.css': 'text' },
    jsx: 'transform',
    tsconfig: join(root, 'tsconfig.build.json'),
    logLevel: 'info',
    ...overrides,
  }
}

export async function buildClientBundle(outfile = join(root, 'lib', 'client.js'), overrides = {}) {
  const TMP_BUNDLE = join(root, 'lib', '_client.bundle.js')
  mkdirSync(dirname(TMP_BUNDLE), { recursive: true })
  await build(clientOptions({ outfile: TMP_BUNDLE, ...overrides }))
  const body = readFileSync(TMP_BUNDLE, 'utf8')
  rmSync(TMP_BUNDLE)
  const wrapped = [
    NOTICE_BANNER,
    '// Generated by build.mjs from src/client/* — do not edit directly.',
    'window.__ModuleLoader__.load({ id: "@samanhappy/dsh-workbench", factory: (require) => {',
    'var module = { exports: {} };',
    'var exports = module.exports;',
    body,
    'return module.exports;',
    '} });',
    '',
  ].join('\n')
  writeFileSync(outfile, wrapped)
  log(`wrote ${outfile} (${Buffer.byteLength(wrapped)} bytes)`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await buildHostBundle()
  log('wrote index.js')
  await buildClientBundle()
}
